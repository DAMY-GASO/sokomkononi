const esc = (v) =>
  String(v ?? "—")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

function fmtDate(v, lang) {
  if (!v) return "—";
  const d = new Date(v);
  if (Number.isNaN(d.getTime())) return "—";
  return d.toLocaleString(lang === "sw" ? "sw-TZ" : "en-US", {
    timeZone: "Africa/Dar_es_Salaam",
  });
}

export function buildRefundReceiptHtml(refund, lang, formatMoney) {
  const t = (sw, en) => (lang === "sw" ? sw : en);
  const money = formatMoney ? formatMoney(refund.amountPaid) : refund.amountPaid;
  const ref = refund.refundReference || `REF-${refund.id}`;

  const rows = [
    [t("Namba ya Rejesho", "Refund Reference"), ref],
    [t("Hali", "Status"), t("Imelipwa", "Paid")],
    [t("Mtumiaji", "User"), refund.userName || `User #${refund.userId}`],
    [t("Simu", "Phone"), refund.userPhone],
    [t("Barua pepe", "Email"), refund.userEmail],
    [
      t("Promotion", "Promotion"),
      `${String(refund.promotionType || "").toUpperCase()} #${refund.promotionId}`,
    ],
    [t("Sababu", "Reason"), refund.reason],
    [t("Njia ya malipo", "Payment method"), refund.method],
    [t("Iliombwa", "Requested"), fmtDate(refund.createdAt, lang)],
    [t("Ililipwa", "Paid on"), fmtDate(refund.completedAt, lang)],
    [t("Maelezo ya admin", "Admin note"), refund.adminNote],
  ].filter(([, v]) => v !== undefined && v !== null && v !== "");

  return `<!doctype html>
<html lang="${lang === "sw" ? "sw" : "en"}">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${esc(t("Risiti ya Rejesho", "Refund Receipt"))} ${esc(ref)}</title>
<style>
  body{font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;background:#f5f3ec;margin:0;padding:24px;color:#101a2e}
  .card{max-width:520px;margin:0 auto;background:#fff;border:1px solid #e5e1d3;border-radius:14px;padding:28px}
  h1{font-size:18px;margin:0 0 4px}
  .sub{font-size:12px;color:#6b7280;margin:0 0 20px}
  .amount{font-size:28px;font-weight:700;margin:0 0 20px;color:#2f6d4f}
  table{width:100%;border-collapse:collapse;font-size:13px}
  td{padding:8px 0;border-top:1px solid #eee;vertical-align:top}
  td:first-child{color:#6b7280;width:42%}
  .foot{margin-top:20px;font-size:11px;color:#9ca3af}
  @media print{body{background:#fff;padding:0}.card{border:none}}
</style>
</head>
<body>
  <div class="card">
    <h1>${esc(t("Risiti ya Rejesho", "Refund Receipt"))}</h1>
    <p class="sub">${esc(t("Imetolewa", "Generated"))}: ${esc(fmtDate(new Date(), lang))}</p>
    <p class="amount">${esc(money)}</p>
    <table>
      ${rows.map(([k, v]) => `<tr><td>${esc(k)}</td><td>${esc(v)}</td></tr>`).join("\n      ")}
    </table>
    <p class="foot">${esc(t("Risiti hii imetengenezwa na mfumo wa admin.", "This receipt was generated by the admin system."))}</p>
  </div>
</body>
</html>`;
}

export function downloadRefundReceipt(refund, lang, formatMoney) {
  const html = buildRefundReceiptHtml(refund, lang, formatMoney);
  const blob = new Blob([html], { type: "text/html;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `refund-receipt-${refund.refundReference || refund.id}.html`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 10_000);
}
