// Inatengeneza risiti ya refund (HTML ya kujitegemea) na kuipakua.
// Haihitaji backend — inatumia data ambayo refundsStore tayari ina.
// Mtumiaji anaweza kuifungua na kuprint/Save as PDF kutoka browser.
